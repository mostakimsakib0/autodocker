"""Open Babel version policy, OB_RANDOM_SEED and the PDBQT header records of
Open Babel >= 3.2 (see docs/openbabel.md)."""
import logging
import os
import subprocess

import pytest

import runner
import vspipeline.protein as prot
import vspipeline.utils as u

needs_obabel = pytest.mark.skipif(runner.OBABEL is None, reason="obabel not available")
OBABEL_VERSION = u.obabel_version() if runner.OBABEL else None
SEEDABLE = OBABEL_VERSION is not None and OBABEL_VERSION >= u.OBABEL_SEEDABLE_VERSION
needs_seedable_obabel = pytest.mark.skipif(
    not SEEDABLE, reason=f"Open Babel >= 3.2.0 needed (found {OBABEL_VERSION})")

# Two waters (whose hydrogens Open Babel places at random) next to a glycine.
WATER_RECEPTOR = (
    "ATOM      1  N   GLY A   1       0.000   0.000   0.000  1.00  0.00           N\n"
    "ATOM      2  CA  GLY A   1       1.458   0.000   0.000  1.00  0.00           C\n"
    "ATOM      3  C   GLY A   1       2.009   1.420   0.000  1.00  0.00           C\n"
    "ATOM      4  O   GLY A   1       1.251   2.390   0.000  1.00  0.00           O\n"
    "ATOM      5  OXT GLY A   1       3.250   1.550   0.000  1.00  0.00           O\n"
    "HETATM    6  O   HOH A 101       5.000   5.000   5.000  1.00  0.00           O\n"
    "HETATM    7  O   HOH A 102      -5.000   5.000   5.000  1.00  0.00           O\n"
    "END\n")


def test_parse_obabel_version():
    assert u.parse_obabel_version("Open Babel 3.2.1 -- Jul 11 2026 -- 20:00:26") == (3, 2, 1)
    assert u.parse_obabel_version("Open Babel 3.1.0 -- Oct 24 2020 -- 12:00:00") == (3, 1, 0)
    assert u.parse_obabel_version("garbage") is None


@needs_obabel
def test_test_environment_has_open_babel_3_2():
    """CI and the image run Open Babel >= 3.2.0. Elsewhere (e.g. a
    distribution's 3.1.1) this is a skip unless
    AUTODOCKER_REQUIRE_OPENBABEL_3_2=1 makes it a failure."""
    if not SEEDABLE and os.environ.get("AUTODOCKER_REQUIRE_OPENBABEL_3_2") != "1":
        pytest.skip(f"Open Babel {OBABEL_VERSION} < 3.2.0 (set "
                    "AUTODOCKER_REQUIRE_OPENBABEL_3_2=1 to fail instead)")
    assert OBABEL_VERSION is not None and OBABEL_VERSION >= (3, 2, 0), OBABEL_VERSION


def _protonate_raw(tmp_path, name, seed):
    src = tmp_path / "rec.pdb"
    src.write_text(WATER_RECEPTOR)
    out = tmp_path / name
    env = {**os.environ, "OMP_NUM_THREADS": "1"}
    env.pop("OB_RANDOM_SEED", None)
    if seed is not None:
        env["OB_RANDOM_SEED"] = str(seed)
    subprocess.run([runner.OBABEL, "-ipdb", str(src), "-opdbqt", "-O", str(out), "-xr",
                    "-p", "7.4", "--partialcharge", "gasteiger"],
                   check=True, capture_output=True, env=env)
    return out.read_bytes()


@needs_obabel
@needs_seedable_obabel
def test_ob_random_seed_makes_water_hydrogens_reproducible(tmp_path):
    same = {_protonate_raw(tmp_path, f"s42_{i}.pdbqt", 42) for i in range(3)}
    assert len(same) == 1
    # Another seed moves the randomly placed water hydrogens.
    assert _protonate_raw(tmp_path, "s43.pdbqt", 43) not in same


@needs_obabel
def test_receptor_preparation_does_not_depend_on_the_seed(tmp_path):
    """The run seed reaches Open Babel, but the hydrogens it places at random
    are re-placed from heavy-atom geometry, so the receptor is the same for
    every seed (and with Open Babel 3.1, which ignores the seed)."""
    src = tmp_path / "rec.pdb"
    src.write_text(WATER_RECEPTOR)
    outputs = set()
    for i, seed in enumerate((42, 42, 43, 2 ** 31 - 1)):
        out = tmp_path / f"run{i}"
        out.mkdir()
        pp = prot.ProteinPreparation(str(src), str(out), seed=seed)
        pp.prepare_receptor("A", keep_hetero=True)
        outputs.add(open(pp.receptor_pdbqt, "rb").read())
    assert len(outputs) == 1


def test_strip_pdbqt_header_records(tmp_path):
    p = tmp_path / "lig.pdbqt"
    p.write_text("REMARK  Name = lig.pdb\n"
                 "COMPND    /some/where/lig.pdb \n"
                 "AUTHOR    GENERATED BY OPEN BABEL 3.2.1\n"
                 "REMARK   2 RESOLUTION. 2.00 ANGSTROMS.\n"
                 "REMARK  1 active torsions:\n"
                 "REMARK  status: ('A' for Active; 'I' for Inactive)\n"
                 "ROOT\n"
                 "ATOM      1  C   UNL     1       0.000   0.000   0.000  0.00  0.00    +0.000 C \n"
                 "ENDROOT\n"
                 "TORSDOF 1\n")
    u._strip_pdbqt_header_records(str(p))
    assert p.read_text().splitlines()[:3] == [
        "REMARK  Name = lig.pdb", "REMARK  1 active torsions:",
        "REMARK  status: ('A' for Active; 'I' for Inactive)"]
    # A rigid (-xr) PDBQT: the header block ends at the first atom.
    p.write_text("REMARK  Name = rec\nCOMPND    UNNAMED\nAUTHOR    X\n"
                 "ATOM      1  C   UNL     1       0.000   0.000   0.000  0.00  0.00    +0.000 C \n")
    u._strip_pdbqt_header_records(str(p))
    assert [line[:6] for line in p.read_text().splitlines()] == ["REMARK", "ATOM  "]
    # A PDBQT input: its REMARK lines (own torsion list) are copied before
    # Open Babel's torsion list; only the last list is kept.
    own = ["REMARK  1 active torsions:",
           "REMARK  status: ('A' for Active; 'I' for Inactive)",
           "REMARK    1  A    between atoms: C_1  and  C_2"]
    p.write_text("\n".join(["REMARK  Name = x", "REMARK  Name = x"] + own + own
                           + ["ROOT", "ENDROOT", "TORSDOF 1"]) + "\n")
    u._strip_pdbqt_header_records(str(p))
    assert p.read_text().splitlines() == ["REMARK  Name = x"] + own + [
        "ROOT", "ENDROOT", "TORSDOF 1"]


# Record names AutoDock Vina's PDBQT parser accepts in a ligand.
VINA_LIGAND_RECORDS = ("REMARK", "ROOT", "ENDROOT", "BRANCH", "ENDBRANCH", "TORSDOF",
                       "ATOM", "HETATM", "WARNING")


@needs_obabel
def test_run_obabel_pdbqt_has_only_vina_records(tmp_path):
    """Open Babel >= 3.2 writes the COMPND/AUTHOR records of a PDB input into
    the PDBQT, which Vina rejects; run_obabel removes them."""
    pdb = tmp_path / "in.pdb"
    pdb.write_text("COMPND    some/path/in.pdb\n"
                   "AUTHOR    SOMEONE\n"
                   "HETATM    1  C1  LIG     1       0.000   0.000   0.000  1.00  0.00           C\n"
                   "HETATM    2  C2  LIG     1       1.520   0.000   0.000  1.00  0.00           C\n"
                   "HETATM    3  O3  LIG     1       2.020   1.300   0.000  1.00  0.00           O\n"
                   "CONECT    1    2\nCONECT    2    3\nEND\n")
    out = tmp_path / "out.pdbqt"
    u.run_obabel(["-ipdb", str(pdb), "-opdbqt", "-O", str(out), "-h",
                  "--partialcharge", "gasteiger"], outputs=[str(out)])
    records = {line.split()[0] for line in out.read_text().splitlines() if line.strip()}
    assert records <= set(VINA_LIGAND_RECORDS), records


def test_check_openbabel_policy(monkeypatch, caplog):
    monkeypatch.setattr(runner, "obabel_version", lambda path=None: (3, 1, 1))
    with caplog.at_level(logging.WARNING, logger="runner"):
        info = runner._check_openbabel(42)
    assert "Open Babel 3.1.1 found" in caplog.text and "NOT comparable" in caplog.text
    assert info["openbabel_version"] == "3.1.1"
    assert info["openbabel_random_seed"]["honoured"] is False
    assert info["openbabel_random_seed"]["value"] == 42
    assert info["openbabel_random_seed"]["hydrogen_probe_values"] == [43, 44]

    caplog.clear()
    monkeypatch.setattr(runner, "obabel_version", lambda path=None: (3, 2, 1))
    with caplog.at_level(logging.WARNING, logger="runner"):
        info = runner._check_openbabel(7)
    assert not caplog.text
    assert info["openbabel_version"] == "3.2.1"
    assert info["openbabel_random_seed"]["honoured"] is True
    assert info["openbabel_random_seed"]["variable"] == "OB_RANDOM_SEED"
